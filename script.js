function initializeRoadmapFilters() {
  const buttons = document.querySelectorAll("[data-roadmap-filter]");
  const cards = document.querySelectorAll(".roadmap-card[data-roadmap-status]");
  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      const filter = button.dataset.roadmapFilter;
      buttons.forEach((candidate) => {
        const selected = candidate === button;
        candidate.classList.toggle("is-active", selected);
        candidate.setAttribute("aria-pressed", String(selected));
      });
      let shown = 0;
      cards.forEach((card) => {
        card.hidden = filter !== "all" && card.dataset.roadmapStatus !== filter;
        if (!card.hidden) shown += 1;
      });
      const emptyMessage = document.querySelector(".resource-empty-message");
      if (emptyMessage) emptyMessage.hidden = shown > 0;
    });
  });
}

function trapDialogFocus(event) {
  if (event.key === "Escape") {
    event.preventDefault();
    closePrivacyDialog();
    return;
  }
  if (event.key !== "Tab") return;
  const dialog = event.currentTarget;
  const focusable = [...dialog.querySelectorAll('button:not([disabled]), input:not([disabled]), a[href]')];
  if (!focusable.length) return;
  const first = focusable[0];
  const last = focusable[focusable.length - 1];
  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
}

function handleConsentAction(action) {
  let choices;
  if (action === "accept") {
    choices = { necessary: true, preferences: true, analytics: true, marketing: true };
  } else if (action === "reject") {
    choices = { ...defaultConsent };
  } else if (action === "save") {
    const dialog = document.getElementById("privacy-settings-dialog");
    choices = {
      necessary: true,
      preferences: dialog.querySelector('input[name="preferences"]').checked,
      analytics: dialog.querySelector('input[name="analytics"]').checked,
      marketing: dialog.querySelector('input[name="marketing"]').checked
    };
  } else if (action === "customize") {
    openPrivacyDialog();
    return;
  } else {
    return;
  }

  if (!saveConsent(choices)) return;
  hideConsentBanner();
  closePrivacyDialog();
}

