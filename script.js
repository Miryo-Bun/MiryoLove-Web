function setLanguage(language, persist = true) {
  const dictionary = translations[language];
  if (!dictionary) return;

  document.documentElement.lang = language;
  const pageTitle = dictionary[document.body.dataset.pageTitleKey] || dictionary.pageTitle;
  const pageDescription = dictionary[document.body.dataset.pageDescriptionKey] || dictionary.metaDescription;
  document.title = pageTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", pageDescription);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", pageTitle);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", pageDescription);
  document.querySelector('meta[property="og:locale"]')?.setAttribute("content", language === "ru" ? "ru_RU" : "en_US");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation !== undefined) element.textContent = translation;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nAlt];
    if (translation !== undefined) element.setAttribute("alt", translation);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const translation = dictionary[element.dataset.i18nAriaLabel];
    if (translation !== undefined) element.setAttribute("aria-label", translation);
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  renderProjectPage(language);
  renderLegalPage(language);
  renderResourcePage(language);
  const socialTitle = document.querySelector('meta[property="og:title"]')?.content || document.title;
  const socialDescription =
    document.querySelector('meta[property="og:description"]')?.content ||
    document.querySelector('meta[name="description"]')?.content ||
    "";
  document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", socialTitle);
  document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", socialDescription);
  const socialImage = document.querySelector('meta[property="og:image"]')?.content;
  if (socialImage) document.querySelector('meta[name="twitter:image"]')?.setAttribute("content", socialImage);
  document.querySelector('meta[property="og:image:alt"]')?.setAttribute("content", dictionary.altMiryoLove);
  if (persist) saveLanguage(language);
  closeMenu();
  initializeReveal();
}

