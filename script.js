function renderLegalPage(language) {
  const legalMain = document.querySelector("[data-legal]");
  if (!legalMain) return;
  const page = legalPages[language]?.[legalMain.dataset.legal];
  if (!page) return;

  const root = legalMain.dataset.root || "./";
  const back = document.createElement("a");
  back.className = "button button-secondary legal-back-link";
  back.href = `${root}index.html`;
  back.textContent = translations[language].backToSite;

  const breadcrumb = document.createElement("nav");
  breadcrumb.className = "project-breadcrumb";
  breadcrumb.setAttribute("aria-label", translations[language].breadcrumb);
  const breadcrumbLink = document.createElement("a");
  breadcrumbLink.href = `${root}index.html`;
  breadcrumbLink.textContent = translations[language].navHome;
  const breadcrumbCurrent = document.createElement("span");
  breadcrumbCurrent.setAttribute("aria-current", "page");
  breadcrumbCurrent.textContent = page.title;
  const separator = document.createElement("span");
  separator.setAttribute("aria-hidden", "true");
  separator.textContent = "/";
  breadcrumb.append(breadcrumbLink, separator, breadcrumbCurrent);

  const heading = document.createElement("h1");
  heading.className = "legal-title";
  heading.textContent = page.title;
  const intro = document.createElement("p");
  intro.className = "legal-intro";
  intro.textContent = page.description;
  const updated = document.createElement("p");
  updated.className = "legal-updated";
  updated.textContent = translations[language].legalUpdated;
  const content = document.createElement("div");
  content.className = "legal-content glass-panel";

  page.sections.forEach((section) => {
    const article = document.createElement("section");
    article.className = "legal-section";
    const sectionHeading = document.createElement("h2");
    sectionHeading.textContent = section.title;
    article.append(sectionHeading);
    section.paragraphs.forEach((text) => {
      const paragraph = document.createElement("p");
      paragraph.textContent = text;
      article.append(paragraph);
    });
    if (section.items) {
      const list = document.createElement("ul");
      section.items.forEach((text) => {
        const item = document.createElement("li");
        item.textContent = text.replace(/<\/?code>/g, "");
        list.append(item);
      });
      article.append(list);
    }
    content.append(article);
  });

  legalMain.replaceChildren(breadcrumb, heading, intro, updated, content, back);
  document.title = `${page.title} | MiryoLove`;
  document.querySelector('meta[name="description"]')?.setAttribute("content", page.description);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", document.title);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", page.description);
  const canonical = document.querySelector('link[rel="canonical"]');
  if (canonical && legalMain.dataset.canonical) {
    canonical.href = legalMain.dataset.canonical;
    document.querySelector('meta[property="og:url"]')?.setAttribute("content", canonical.href);
  }
}

