function initializeProjectFilters() {
  const filterButtons = document.querySelectorAll("[data-project-filter]");
  if (!filterButtons.length) return;
  const pendingHideTimers = new WeakMap();
  let activeFilter = "all";

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const filter = button.dataset.projectFilter;
      activeFilter = filter;
      filterButtons.forEach((candidate) => {
        const selected = candidate === button;
        candidate.classList.toggle("is-active", selected);
        candidate.setAttribute("aria-pressed", String(selected));
      });

      document.querySelectorAll(".project-card[data-project-status]").forEach((card) => {
        const pendingTimer = pendingHideTimers.get(card);
        if (pendingTimer) window.clearTimeout(pendingTimer);
        pendingHideTimers.delete(card);
        const shouldShow = filter === "all" || card.dataset.projectStatus === filter;
        card.classList.remove("is-filtering-in", "is-filtering-out");
        if (shouldShow === !card.classList.contains("is-hidden")) return;

        if (shouldShow) {
          card.classList.remove("is-hidden");
          requestAnimationFrame(() => {
            if (filter === activeFilter) card.classList.add("is-filtering-in");
          });
        } else {
          card.classList.add("is-filtering-out");
          const timer = window.setTimeout(() => {
            card.classList.add("is-hidden");
            card.classList.remove("is-filtering-out");
            pendingHideTimers.delete(card);
          }, 220);
          pendingHideTimers.set(card, timer);
        }
      });
    });
  });
}

let revealObserver;
function initializeReveal() {
  const candidates = document.querySelectorAll(
    ".hero-copy, .hero-art, .section-heading, .project-card, .about-copy, .about-visual, .principle-card, .community-link, .closing-section, .project-detail-art, .project-screenshot, .project-detail-block, .detail-feature-card, .changelog-entry, .philosophy-card"
  );
  const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (prefersReducedMotion || !("IntersectionObserver" in window)) {
    candidates.forEach((element) => element.classList.add("is-visible"));
    return;
  }

  revealObserver ??= new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -35px 0px" }
  );

  candidates.forEach((element) => {
    if (element.classList.contains("is-visible")) return;
    element.classList.add("will-reveal");
    revealObserver.observe(element);
  });
}

